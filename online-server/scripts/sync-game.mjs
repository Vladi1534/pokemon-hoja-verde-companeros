import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
const frontend=path.resolve(process.argv[2]||'..');
if(!fs.existsSync(path.join(frontend,'coop.js')))throw Error('Indica el directorio del juego de GitHub: node scripts/sync-game.mjs <directorio>');
execFileSync(process.execPath,['build.cjs'],{cwd:frontend,stdio:'inherit'});
fs.copyFileSync(path.join(frontend,'dist/index.html'),'public/play.html');
const context=vm.createContext({});vm.runInContext(fs.readFileSync(path.join(frontend,'coop-world.js'),'utf8')+';this.world=COOP_WORLD',context);
fs.writeFileSync('server/world.json',JSON.stringify(context.world));
